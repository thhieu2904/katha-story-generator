export type UiCopy = Record<keyof typeof vi, string>;

export function getUiCopy(language: ContentLanguage): UiCopy {
  return language === 'km' ? km : vi;
}

export function formatCopy(template: string, values: Record<string, string | number>): string {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}
